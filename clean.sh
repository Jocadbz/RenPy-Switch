#!/usr/bin/env bash
#
# Remove generated build artifacts so the next build is from a clean slate.
#
#   bash clean.sh          # clean RenpySwitch build output (fast to regenerate)
#   bash clean.sh --deep   # also drop switch_deps/ (re-downloads ecdsa next build)
#
# PRESERVES (never touched):
#   - sources/                         hand-written C (main.c, video_player, splash.png, ...)
#   - renpy-source/renpy/  *.py/.pyx   the engine + your Switch port edits
#   - renpy-source/the_question/       the demo game
#   - *.nacp, *.sh, *.patch, CMakeLists.txt, etc.   build inputs/scripts
#   - ../PyNX_.../python_build/libpython3.13.a       the (slow) CPython build
#   - switch_deps/                     fetched pure-python deps (unless --deep)
#
set -e
cd "$(dirname "$0")"

echo "== Cleaning RenpySwitch build artifacts =="

# CMake / cross-compile output (build.bash recreates: rm -rf build; cmake ..)
rm -rf build

# Gathered C + headers (build.bash re-copies from sources/ + tmp/gen3-static + src/)
rm -rf source include

# Packaging staging + the output NRO (regenerated by build.bash / repack_lib.sh)
rm -rf raw renpy_clear
rm -f the_question.nro

# Cython-generated C + host build_ext leftovers (regenerated by the cythonize step)
rm -rf renpy-source/tmp renpy-source/build
find renpy-source/renpy -name '*.so'  -delete 2>/dev/null || true
find renpy-source        -name '*.pyc' -delete 2>/dev/null || true
find renpy-source -name '__pycache__' -type d -prune -exec rm -rf {} + 2>/dev/null || true

# Stray logs
rm -f build*.log setup*.log /tmp/renpy_link.log 2>/dev/null || true

if [ "$1" = "--deep" ]; then
    echo "  --deep: removing switch_deps/ (ecdsa will be re-fetched next build)"
    rm -rf switch_deps
fi

echo "== Done. =="
echo "Preserved: sources/, renpy-source/renpy edits, the_question.nacp, scripts, libpython3.13.a$([ "$1" = "--deep" ] || echo ', switch_deps/')."
echo "Next: sudo bash build.bash   (full rebuild: cythonize -> cross-compile -> package)"
echo "Note: to also rebuild CPython itself (slow), clean it separately in"
echo "      ../PyNX_python3.13.0_horizonOS_switch/python_build/."
