#!/usr/bin/env python3
"""Use upstream's module declarations and Cython generator, without a host link."""
import argparse
from concurrent.futures import ThreadPoolExecutor
import json
import os
from pathlib import Path
import re
import runpy
import sys


def generate(source, output, jobs):
    source = source.resolve()
    output = output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    os.chdir(source)
    os.environ.update(RENPY_STATIC="1", RENPY_NO_ASSIMP="1", CFLAGS="", LDFLAGS="")
    sys.path.insert(0, str(source / "scripts"))
    import setuplib

    # Upstream's parallel generator doesn't inspect Future exceptions. Propagate
    # both Python exceptions and failed Cython subprocesses before emitting a manifest.
    def generate_all():
        with ThreadPoolExecutor(max_workers=jobs) as pool:
            futures = [pool.submit(setuplib.generate_cython, *args) for args in setuplib.generate_cython_queue]
            for future in futures:
                future.result()
        if setuplib.cython_failure:
            raise RuntimeError("Cython generation failed")

    upstream_cython = setuplib.cython

    def cython(name, *args, **kwargs):
        if name == "renpy.tfd":
            return  # native desktop file dialogs have no Horizon backend
        upstream_cython(name, *args, **kwargs)

    setuplib.generate_all_cython = generate_all
    setuplib.cython = cython
    sys.argv = [str(source / "setup.py"), "generate"]
    runpy.run_path(sys.argv[0], run_name="__main__")
    sources = set()
    modules = []
    for ext in setuplib.extensions:
        symbol = "PyInit_" + ext.name.replace(".", "_")
        generated = source / ext.sources[0]
        if not generated.is_file() or not re.search(r"\b" + symbol + r"\s*\(", generated.read_text()):
            raise RuntimeError(f"Missing static initializer {symbol} in {generated}")
        modules.append((ext.name, symbol))
        for name in ext.sources:
            path = source / name
            if not path.is_file():
                raise RuntimeError(f"Missing module source {path}")
            sources.add(path)
    (output / "modules.json").write_text(json.dumps(dict(modules), indent=2) + "\n")
    (output / "modules.cmake").write_text("set(RENPY_MODULE_SOURCES\n" + "".join(f'  "{p.as_posix()}"\n' for p in sorted(sources)) + ")\n")
    (output / "module_declarations.h").write_text("/* Generated by tools/generate_modules.py. */\n" + "".join(f"PyMODINIT_FUNC {sym}(void);\n" for _, sym in modules))
    (output / "module_entries.h").write_text("/* Generated by tools/generate_modules.py. */\n" + "".join(f'{{"{name}", {sym}}},\n' for name, sym in modules))
    print(f"Generated and validated {len(modules)} native modules, {len(sources)} C sources")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--jobs", type=int, default=4)
    args = parser.parse_args()
    generate(args.source, args.output, args.jobs)
